const water = (id: string) => screen.getByRole("button", { name: `Inspect water target ${id}` });
const inspector = () => screen.getByRole("region", { name: "Target viewability" });
async function openSettings(user: ReturnType<typeof userEvent.setup>) {
  await user.click(await screen.findByRole("button", { name: "Map tools" }));
  await user.click(screen.getByRole("button", { name: "Settings" }));
}
async function setLayer(user: ReturnType<typeof userEvent.setup>, metric: string) {
  const toggle = await screen.findByRole("button", { name: "Map layers" });
  if (toggle.getAttribute("aria-expanded") !== "true") await user.click(toggle);
  await user.selectOptions(screen.getByLabelText("Map layer"), metric);
}
async function setScore(user: ReturnType<typeof userEvent.setup>, metric: adapter.ViewMetric) {
  const names: Record<adapter.ViewMetric, string> = { lower: "Lower estimate", upper: "Upper estimate", average_viewability: "Complete score",
    input_unknown_fraction: "Input uncertainty", above_ground_lower: "Above-ground weight (lower)", weight_above_ground: "Above-ground weight (complete)",
    weight_distance: "Distance weight", weight_terrain: "Terrain weight" };
  await user.click(screen.getByRole("button", { name: "Score display" }));
  await user.click(screen.getByRole("button", { name: `Select ${names[metric]}` }));
}
